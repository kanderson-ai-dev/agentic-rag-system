"""Dashboard endpoints feeding usage aggregates to the frontend."""

import json
from pathlib import Path
from typing import Any

from fastapi import APIRouter, Depends, Request

from app.core.config import Settings, get_settings
from app.core.dependencies import get_session_id
from app.services.usage_store import UsageStore

router = APIRouter(prefix="/api/v1/dashboard", tags=["dashboard"])

_SCORECARD_PATH = (
    Path(__file__).resolve().parents[4] / "evaluation" / "results" / "ragas_scorecard.json"
)
_BASELINE_PATH = (
    Path(__file__).resolve().parents[4]
    / "evaluation"
    / "results"
    / "baseline_comparison.json"
)


def _get_usage_store(request: Request) -> UsageStore:
    store: UsageStore = request.app.state.usage_store
    return store


@router.get("/summary")
def summary(
    request: Request, session_id: str | None = Depends(get_session_id)
) -> dict[str, Any]:
    """Return aggregate usage metrics (total cost, latency, blocked, reviews).

    Scoped to the caller's `X-Session-Id` when present, so a fresh browser
    session starts at zero instead of showing the service's lifetime totals;
    omit the header (e.g. from an ops script) to get the full aggregate.
    """
    return _get_usage_store(request).summary(session_id=session_id)


@router.get("/recent")
def recent(
    request: Request, limit: int = 20, session_id: str | None = Depends(get_session_id)
) -> list[dict[str, Any]]:
    """Return the most recent requests' usage metadata, scoped like `/summary`."""
    return _get_usage_store(request).recent(limit=limit, session_id=session_id)


def _human_vs_agent(
    perf: dict[str, Any], settings: Settings
) -> dict[str, Any]:
    """Compare the measured agent cost/time to an estimated human baseline.

    The human side is a stated assumption (minutes + hourly rate from
    settings) — it is labelled an estimate in the payload and in the UI.
    The agent side uses only real, session-scoped aggregates.
    """
    human_minutes = settings.human_minutes_per_query
    human_hourly = settings.human_hourly_usd
    human_cost_per_query = human_hourly * (human_minutes / 60.0)
    requests = perf["requests"]
    agent_cost = perf["cost"]["avg_per_query_usd"]
    agent_seconds = perf["latency"]["p50_ms"] / 1000.0
    human_total = human_cost_per_query * requests
    agent_total = perf["cost"]["total_usd"]
    savings_pct = (
        (1 - agent_total / human_total) * 100.0 if human_total > 0 else 0.0
    )
    return {
        "label": "estimate",
        "assumptions": {
            "human_minutes_per_query": human_minutes,
            "human_hourly_usd": human_hourly,
        },
        "per_query": {
            "human_cost_usd": human_cost_per_query,
            "human_seconds": human_minutes * 60.0,
            "agent_cost_usd": agent_cost,
            "agent_seconds": agent_seconds,
        },
        "totals": {
            "requests": requests,
            "human_cost_usd": human_total,
            "agent_cost_usd": agent_total,
        },
        "cost_savings_pct": savings_pct,
    }


@router.get("/performance")
def performance(
    request: Request,
    session_id: str | None = Depends(get_session_id),
    settings: Settings = Depends(get_settings),
) -> dict[str, Any]:
    """Session-scoped performance telemetry for the dashboard panel.

    Per-node p50/p95 latency (persisted per request), end-to-end p50/p95,
    average and accumulated cost, tokens/query, a 7-day cost trend,
    block/escalation rates and per-prompt-version aggregates — plus the
    Human-vs-Agent comparison with its assumptions echoed back.
    """
    perf = _get_usage_store(request).performance(session_id=session_id)
    perf["human_vs_agent"] = _human_vs_agent(perf, settings)
    # The daily budget gate lands in a later phase; the field is echoed when
    # configured so the panel can already render the slot.
    perf["budget"] = {
        "daily_limit_usd": getattr(settings, "daily_budget_usd", None)
    }
    return perf


# Success thresholds from the project's "Objetivo del proyecto" (PLAN.md / README.md).
_QUALITY_THRESHOLDS = {
    "faithfulness": 0.85,
    "answer_relevancy": 0.85,
    "context_precision": 0.75,
    "context_recall": 0.75,
}


@router.get("/quality")
def quality() -> dict[str, Any]:
    """Return the latest EDD scorecard (RAGAS-style metrics) with pass/fail flags.

    Surfaces the same numbers published in the README, generated by
    `evaluation/run_ragas.py`, so the operational dashboard is never
    disconnected from the project's quality thresholds — cost and latency
    without a quality signal is an incomplete picture of a RAG system.
    """
    if not _SCORECARD_PATH.exists():
        return {"available": False}

    scorecard = json.loads(_SCORECARD_PATH.read_text(encoding="utf-8"))
    metrics = {
        name: {
            "score": scorecard.get(name),
            "threshold": threshold,
            "passing": (scorecard.get(name) or 0) >= threshold,
        }
        for name, threshold in _QUALITY_THRESHOLDS.items()
    }
    response: dict[str, Any] = {
        "available": True,
        "generated_at": scorecard.get("generated_at"),
        "metrics": metrics,
    }
    # Retrieval-mode comparison lands here once `run_baseline.py` has run —
    # the headline metrics per mode, not the full per-case detail.
    if _BASELINE_PATH.exists():
        comparison = json.loads(_BASELINE_PATH.read_text(encoding="utf-8"))
        keys = (
            "faithfulness",
            "answer_relevancy",
            "context_precision",
            "context_recall",
            "llm_as_judge",
            "behavior_accuracy",
            "cost_per_query_usd",
            "latency_p50_ms",
            "latency_p95_ms",
        )
        response["baseline_comparison"] = {
            "generated_at": comparison.get("meta", {}).get("generated_at"),
            "modes": {
                mode: {key: card.get(key) for key in keys}
                for mode, card in comparison.get("modes", {}).items()
            },
            "multi_hop": {
                mode: card.get("per_category", {}).get("multi_hop")
                for mode, card in comparison.get("modes", {}).items()
            },
        }
    return response
